import { browser, platformPage, SHOT } from "./qa-tmp-lib.mjs";
const b = await browser();
const p = await platformPage(b, { path: "/platform/settings/roles/new" });
await p.getByLabel("名字").fill("验收测试角色 M4-05");
await p.getByLabel("说明（选填）").fill("验收测试：供应商审核、渠道审核、订单查看、待审核、财务结算查看；只看东京和验收测试渠道 M3-07");
for (const n of ["供应商 · 审核", "渠道 · 审核", "订单 · 查看", "待审核 · 查看", "财务结算 · 查看"]) await p.getByRole("checkbox", { name: n, exact: true }).check();
console.log("供应商查看 auto-checked:", await p.getByRole("checkbox", { name: "供应商 · 查看", exact: true }).isChecked());
await p.getByLabel("只看选中的城市").check();
await p.getByRole("combobox", { name: "城市" }).fill("东京"); await p.waitForTimeout(1200);
await p.getByRole("option", { name: /东京/ }).first().click();
await p.getByLabel("只看选中的渠道").check();
await p.getByRole("combobox", { name: "渠道" }).fill("M3-07"); await p.waitForTimeout(1200);
await p.getByRole("option", { name: /M3-07/ }).first().click();
await p.waitForTimeout(500);
await p.screenshot({ path: SHOT + "M4-05-role-form-filled.png", fullPage: false });
await p.getByRole("button", { name: "新建" }).click(); await p.waitForTimeout(2500);
console.log(p.url());
console.log((await p.locator("main").innerText()).slice(0,2500));
await p.screenshot({ path: SHOT + "M4-05-role-created.png", fullPage: true });
